CREATE TABLE construction.quality_records (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL,
  project_id uuid NOT NULL,
  reference text NOT NULL,
  kind text NOT NULL CHECK(kind IN ('itp','wir','ncr','pour','laboratory','reinforcement')),
  title text NOT NULL,
  state text NOT NULL DEFAULT 'draft' CHECK(state IN ('draft','submitted','revision_required','reviewed','closed')),
  revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
  fields jsonb NOT NULL CHECK(jsonb_typeof(fields)='object'),
  due_on date,
  element_id uuid,
  delivery_id uuid,
  specification_id uuid,
  related_id uuid,
  document_id uuid,
  document_revision integer,
  author uuid NOT NULL,
  reviewer uuid,
  CHECK(reviewer IS NULL OR reviewer<>author),
  CHECK((document_id IS NULL)=(document_revision IS NULL)),
  UNIQUE(organization_id,project_id,kind,reference),
  UNIQUE(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id) REFERENCES construction.projects(organization_id,id),
  FOREIGN KEY(organization_id,project_id,element_id) REFERENCES construction.elements(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id,delivery_id) REFERENCES construction.deliveries(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id,specification_id) REFERENCES construction.specifications(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id,related_id) REFERENCES construction.quality_records(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id,document_id,document_revision) REFERENCES construction.document_revisions(organization_id,project_id,document_id,revision),
  FOREIGN KEY(organization_id,author) REFERENCES construction.members(organization_id,account_id),
  FOREIGN KEY(organization_id,reviewer) REFERENCES construction.members(organization_id,account_id)
);
CREATE INDEX ON construction.quality_records(organization_id,project_id,kind,id);
CREATE INDEX ON construction.quality_records(organization_id,project_id,due_on) WHERE state NOT IN ('reviewed','closed');
