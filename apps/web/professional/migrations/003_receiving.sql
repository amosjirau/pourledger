CREATE TABLE construction.deliveries (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL,
  project_id uuid NOT NULL,
  reference text NOT NULL,
  material text NOT NULL,
  supplier text NOT NULL,
  supplier_key text NOT NULL,
  delivery_note text NOT NULL,
  line text NOT NULL,
  delivery_date date NOT NULL,
  quantity numeric(20,6) NOT NULL CHECK(quantity>0),
  unit text NOT NULL,
  metadata jsonb NOT NULL,
  author uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(organization_id,project_id,reference),
  UNIQUE(organization_id,project_id,supplier_key,delivery_note,line),
  UNIQUE(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id) REFERENCES construction.projects(organization_id,id),
  FOREIGN KEY(organization_id,author) REFERENCES construction.members(organization_id,account_id)
);
CREATE INDEX ON construction.deliveries(organization_id,project_id,delivery_date DESC,id DESC);
CREATE TYPE construction.mir_state AS ENUM ('draft','submitted','under_review','revision_required','accepted','partially_accepted','rejected');
CREATE TABLE construction.inspection_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL,
  project_id uuid NOT NULL,
  delivery_id uuid NOT NULL,
  reference text NOT NULL,
  status construction.mir_state NOT NULL DEFAULT 'draft',
  revision integer NOT NULL DEFAULT 1 CHECK(revision>0),
  inspection_date date,
  metadata jsonb NOT NULL DEFAULT '{}',
  document_id uuid,
  document_revision integer,
  CHECK ((document_id IS NULL)=(document_revision IS NULL)),
  accepted numeric(20,6) CHECK(accepted>=0),
  rejected numeric(20,6) CHECK(rejected>=0),
  quarantined numeric(20,6) CHECK(quarantined>=0),
  CHECK((status IN ('accepted','partially_accepted','rejected'))=(accepted IS NOT NULL AND rejected IS NOT NULL AND quarantined IS NOT NULL)),
  author uuid NOT NULL,
  reviewer uuid,
  CHECK(reviewer IS NULL OR author<>reviewer),
  UNIQUE(organization_id,project_id,reference),
  UNIQUE(organization_id,project_id,delivery_id),
  FOREIGN KEY(organization_id,project_id,delivery_id) REFERENCES construction.deliveries(organization_id,project_id,id),
  FOREIGN KEY(organization_id,project_id,document_id,document_revision) REFERENCES construction.document_revisions(organization_id,project_id,document_id,revision),
  FOREIGN KEY(organization_id,author) REFERENCES construction.members(organization_id,account_id),
  FOREIGN KEY(organization_id,reviewer) REFERENCES construction.members(organization_id,account_id)
);
